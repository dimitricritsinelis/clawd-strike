export type BuildR8AtmosphereOptions = {
  seed: number;
  wallMaterials: WallMaterialLibrary | null;
  wallQuality: WallTextureQuality;
  palmQuality: WallTextureQuality;
  floorTopY: number;
  data?: R8Atmosphere;
};

export function buildR8Atmosphere(options: BuildR8AtmosphereOptions): Group {
  const data = options.data ?? R8_ATMOSPHERE;
  const root = new Group();
  root.name = "r8-atmosphere";
  const batches = new Batches();
  for (const a of data.awnings) buildAwning(batches, a);
  for (const s of data.spans) buildSpan(batches, s);
  for (const k of data.wallKit) buildWallKit(batches, k);
  for (const d of data.decals ?? []) buildDecal(batches, d);
  for (const r of data.rooftop) buildRooftop(batches, r);
  for (const c of data.clutter) if (!c.model) buildClutterProcedural(batches, c);
  const materials = materialSet(options.wallMaterials, options.wallQuality, options.floorTopY);
  batches.build(root, materials, new Set(["cloth", "appliance", "metalBox", "tank", "roomPlaster", "roomTrim", "panel", "dish", "iron", "brick", "concrete", "timber", "void"]));

  if (data.market) {
    root.add(buildR8Market(data.market, r8MaterialFactory(options.wallMaterials, options.wallQuality, options.floorTopY)));
  }

  if (data.palms.length > 0) {
    const anchors: RuntimeAnchorsSpec = {
      mapId: "bazaar-map",
      anchors: data.palms.map((p) => ({
        id: p.id,
        type: "decorative_palm",
        zone: "R8_ENCLOSED_GARDEN",
        pos: { x: p.pos[0], y: p.pos[1], z: p.pos[2] },
        yawDeg: p.yawDeg,
        widthM: p.widthM,
        heightM: p.heightM,
      })),
    };
    const palms = buildDecorativePalms(anchors, options.seed, options.palmQuality);
    if (palms) root.add(palms);
  }
  root.userData.r8Counts = {
    awnings: data.awnings.length, spans: data.spans.length, wallKit: data.wallKit.length,
    rooftop: data.rooftop.length, clutterProcedural: data.clutter.filter((c) => !c.model).length, palms: data.palms.length,
    marketWallArt: data.market?.wallArt.length ?? 0, marketLanterns: data.market?.lanterns.length ?? 0, marketGoods: data.market?.counterGoods.length ?? 0,
  };
  return root;
}
